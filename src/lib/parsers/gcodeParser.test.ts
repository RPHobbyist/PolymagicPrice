/*
 * The G-code parser produces the two numbers a quote is priced on, and it had no tests at all.
 *
 * The case that prompted these: a weight the slicer never stated was derived as
 * `filamentLengthMm * 0.00298`, which is exactly 1.75 mm PLA. Cura writes filament use in metres
 * and no gram figure, so every Cura file took that path — 2.85 mm filament came out 2.65x light
 * and ABS came out heavy, in the material cost and in the carbon mass alike.
 */
import { describe, it, expect, vi } from "vitest";

/*
 * The parser scrubs 128-character metadata strings (printer model, filament name) with DOMPurify,
 * which needs a DOM; this suite runs in Node, because `vitest.config.ts` is deliberately
 * `environment: "node"` and component testing is out of scope. The stub keeps that step doing
 * what it does in a browser — remove markup — without pulling jsdom into the project.
 */
vi.mock("dompurify", () => ({
    default: { sanitize: (value: string) => String(value).replace(/<[^>]*>/g, "") },
}));

import { parseGcode, filamentWeightFromLength, DEFAULT_FILAMENT_DIAMETER_MM, modelUnitToMm, parseBambuSliceInfo, plateSurfaceArea } from "./gcodeParser";

/** A Cura header: metres of filament, seconds of time, and no weight anywhere. */
const curaHeader = (metres = 3.5, seconds = 5400) => `;FLAVOR:Marlin
;TIME:${seconds}
;Filament used: ${metres}m
;Layer height: 0.2
;MINX:10
;Generated with Cura_SteamEngine 5.7.1
M104 S200
`;

/** PrusaSlicer/Orca write grams directly, plus the filament's diameter and density. */
const prusaHeader = ({
    grams = 24.8,
    diameter = 1.75,
    density = 1.24,
    time = "1h 30m 12s",
}: { grams?: number; diameter?: number; density?: number; time?: string } = {}) => `; generated by PrusaSlicer 2.8.0
; estimated printing time (normal mode) = ${time}
; filament used [mm] = 9999.9
; total filament used [g] = ${grams}
; filament_diameter = ${diameter}
; filament_density = ${density}
; printer_model = MK4
`;

describe("filamentWeightFromLength", () => {
    it("reproduces the old constant for 1.75 mm PLA", () => {
        // The replaced literal was 0.00298 g/mm.
        expect(filamentWeightFromLength(1000, 1.75, 1.24) / 1000).toBeCloseTo(0.00298, 5);
    });

    it("scales with the square of the diameter", () => {
        const thin = filamentWeightFromLength(1000, 1.75, 1.24);
        const thick = filamentWeightFromLength(1000, 2.85, 1.24);

        expect(thick / thin).toBeCloseTo((2.85 / 1.75) ** 2, 3);
    });

    it("scales linearly with density", () => {
        const pla = filamentWeightFromLength(1000, 1.75, 1.24);
        const abs = filamentWeightFromLength(1000, 1.75, 1.04);

        expect(abs / pla).toBeCloseTo(1.04 / 1.24, 5);
    });

    it("falls back to 1.75 mm PLA on implausible inputs and refuses nonsense lengths", () => {
        expect(filamentWeightFromLength(1000, 0, 0)).toBeCloseTo(
            filamentWeightFromLength(1000, DEFAULT_FILAMENT_DIAMETER_MM, 1.24),
            6
        );
        expect(filamentWeightFromLength(-5)).toBe(0);
        expect(filamentWeightFromLength(Number.NaN)).toBe(0);
    });
});

describe("parseGcode — Cura (length only)", () => {
    it("reads time and length, and flags the weight as derived", () => {
        const data = parseGcode(curaHeader(3.5, 5400));

        expect(data.printTimeHours).toBe(1.5);
        expect(data.filamentLengthMm).toBe(3500);
        expect(data.weightFromLength).toBe(true);
        // 3500 mm of 1.75 mm PLA.
        expect(data.filamentWeightGrams).toBeCloseTo(10.4, 1);
    });

    it("reports no diameter or density, so the calculator can use the material's", () => {
        const data = parseGcode(curaHeader());

        expect(data.filamentDiameterMm).toBeUndefined();
        expect(data.filamentDensityGCm3).toBeUndefined();
    });
});

describe("parseGcode — PrusaSlicer (weight stated)", () => {
    it("uses the stated grams and does not mark them as derived", () => {
        const data = parseGcode(prusaHeader({ grams: 24.8 }));

        expect(data.filamentWeightGrams).toBe(24.8);
        expect(data.weightFromLength).toBeUndefined();
        expect(data.printTimeHours).toBeCloseTo(1.5, 2);
        expect(data.printerModel).toBe("MK4");
    });

    it("passes the file's own diameter and density through", () => {
        const data = parseGcode(prusaHeader({ diameter: 2.85, density: 1.04 }));

        expect(data.filamentDiameterMm).toBe(2.85);
        expect(data.filamentDensityGCm3).toBe(1.04);
    });

    it("uses the file's diameter and density when only a length is present", () => {
        const noWeight = `; generated by PrusaSlicer 2.8.0
; estimated printing time (normal mode) = 2h 0m 0s
; filament used [mm] = 1000
; filament_diameter = 2.85
; filament_density = 1.04
`;
        const data = parseGcode(noWeight);

        expect(data.weightFromLength).toBe(true);
        // 1000 mm of 2.85 mm filament at 1.04 g/cm³ = 6.6 g, not the 3.0 g the old constant gave.
        expect(data.filamentWeightGrams).toBeCloseTo(6.6, 1);
    });

    it("ignores implausible stated values rather than pricing on them", () => {
        const data = parseGcode(prusaHeader({ diameter: 175, density: 0 }));

        expect(data.filamentDiameterMm).toBeUndefined();
        expect(data.filamentDensityGCm3).toBeUndefined();
    });
});

describe("parseGcode — general robustness", () => {
    it("returns zeros for content that is not G-code, without throwing", () => {
        const data = parseGcode("this is not a gcode file");

        expect(data.printTimeHours).toBe(0);
        expect(data.filamentWeightGrams).toBe(0);
        expect(data.weightFromLength).toBeUndefined();
    });

    it("reads OrcaSlicer's per-feature weights and derives the waste residue", () => {
        const orca = `; total_filament_used_g = 100
; wall_filament_used_g = 60
; sparse_infill_filament_used_g = 30
; support_filament_used_g = 5
`;
        const data = parseGcode(orca);

        expect(data.filamentWeightGrams).toBe(100);
        expect(data.featureWeights).toEqual({ walls: 60, infill: 30, supports: 5, waste: 5 });
    });

    it("reads Cura's seconds format and PrusaSlicer's day/hour format alike", () => {
        expect(parseGcode(";TIME:3600\n").printTimeHours).toBe(1);
        expect(
            parseGcode("; estimated printing time (normal mode) = 1d 2h 30m 0s\n").printTimeHours
        ).toBe(26.5);
    });
});

describe("parseGcode — multi-extruder and time formats", () => {
    it("sums the per-extruder weights of a two-colour print", () => {
        const data = parseGcode("; filament used [g] = 12.3, 4.5\n; estimated printing time (normal mode) = 1h 0m 0s\n");
        expect(data.filamentWeightGrams).toBeCloseTo(16.8, 5);
    });

    it("reads clock-style and decimal-second times", () => {
        expect(parseGcode("; filament used [g] = 5\n; estimated printing time = 01:30:00\n").printTimeHours).toBeCloseTo(1.5, 5);
        expect(parseGcode("; filament used [g] = 5\n;TIME:5400.5\n").printTimeHours).toBeCloseTo(5400.5 / 3600, 3);
        expect(parseGcode("; filament used [g] = 5\n;PRINT.TIME:3600\n").printTimeHours).toBeCloseTo(1, 5);
    });
});

describe("3MF model units", () => {
    it("converts every unit the spec allows to millimetres", () => {
        expect(modelUnitToMm("inch")).toBe(25.4);
        expect(modelUnitToMm("centimeter")).toBe(10);
        expect(modelUnitToMm("meter")).toBe(1000);
        expect(modelUnitToMm("micron")).toBe(0.001);
        expect(modelUnitToMm(undefined)).toBe(1);
        expect(modelUnitToMm("furlong")).toBe(1);
    });
});

describe("Bambu slice_info.config", () => {
    it("reads the first plate's time and weight", () => {
        const xml = `<config><plate>
          <metadata key="index" value="1"/>
          <metadata key="prediction" value="7200"/>
          <metadata key="weight" value="31.5"/>
          <filament id="1" used_m="10" used_g="20.5"/>
        </plate><plate><metadata key="prediction" value="999"/><metadata key="weight" value="1"/></plate></config>`;
        const data = parseBambuSliceInfo(xml);
        expect(data.printTimeHours).toBe(2);
        expect(data.filamentWeightGrams).toBe(31.5);
    });
    it("falls back to the per-filament figures", () => {
        const xml = `<plate><metadata key="prediction" value="3600"/><filament used_g="10"/><filament used_g="2.5"/></plate>`;
        expect(parseBambuSliceInfo(xml).filamentWeightGrams).toBe(12.5);
    });
});

describe("3MF plate area", () => {
    it("counts every copy of an object and applies each item's scale", () => {
        const objects = new Map([["1", { area: 100, components: [] }]]);
        // two copies, one at double size (area x4)
        expect(plateSurfaceArea(objects, [{ objectId: "1", scale: 1 }, { objectId: "1", scale: 2 }])).toBe(500);
    });
    it("adds the components of an assembled object and ignores objects not on the plate", () => {
        const objects = new Map([
            ["1", { area: 10, components: [{ objectId: "2", scale: 1 }, { objectId: "2", scale: 1 }] }],
            ["2", { area: 5, components: [] }],
            ["3", { area: 999, components: [] }],
        ]);
        expect(plateSurfaceArea(objects, [{ objectId: "1", scale: 1 }])).toBe(20);
    });
    it("survives objects that reference each other", () => {
        const objects = new Map([
            ["1", { area: 1, components: [{ objectId: "2", scale: 1 }] }],
            ["2", { area: 1, components: [{ objectId: "1", scale: 1 }] }],
        ]);
        expect(Number.isFinite(plateSurfaceArea(objects, [{ objectId: "1", scale: 1 }]))).toBe(true);
    });
});
